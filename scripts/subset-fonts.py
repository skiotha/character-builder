"""Re-cut the served web fonts from the originals in fonts-src/.

Dev-only tool (Python, not part of the Node runtime — ADR-001 covers
runtime dependencies). Requires fontTools and brotli:

    python -m pip install fonttools brotli
    python scripts/subset-fonts.py

Writes WOFF2 files into public/assets/fonts/ (deleting the files it no
longer produces) and regenerates public/common/fonts.css, so every
@font-face `unicode-range` always matches the ranges its file was cut
with. Each face is split into a Latin and a Cyrillic file; the browser
downloads a file only when the page uses a character in its range.
Glyphs a font lacks are skipped and fall back per character.

The Latin files of Body regular, Header and Display are preloaded in
public/index.html; update those links when renaming outputs here.
"""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "fonts-src"
OUT = ROOT / "public" / "assets" / "fonts"
CSS = ROOT / "public" / "common" / "fonts.css"
URL = "/assets/fonts"

# Ranges follow the Google Fonts latin / cyrillic splits, plus arrows
# (the counter's "→" in Header).
RANGES = {
    "latin": (
        "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, "
        "U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, "
        "U+2190-2193, U+2212, U+2215, U+FEFF, U+FFFD"
    ),
    "cyrillic": "U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116",
}

# (output stem, source file, CSS family, font-style, subsets or literal text)
FACES = [
    ("body-regular", "philosopher.ttf", "Nagara Body", "normal", ["latin", "cyrillic"]),
    ("body-italic", "philosopher-italic.ttf", "Nagara Body", "italic", ["latin", "cyrillic"]),
    ("header", "zenkurenaido.ttf", "Nagara Header", "normal", ["latin", "cyrillic"]),
    # Wordmark cut: only the letters of "Nagara". Widen to the latin /
    # cyrillic split once a design sets other text in Display.
    ("display", "toruksc.ttf", "Nagara Display", "normal", {"wordmark": "NAGRagr "}),
]


def parse_ranges(spec: str) -> list[int]:
    codepoints: list[int] = []
    for part in spec.split(","):
        part = part.strip().removeprefix("U+")
        lo, _, hi = part.partition("-")
        codepoints.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return codepoints


def cut(source: Path, target: Path, unicodes: list[int]) -> None:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    font = TTFont(source, recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(target)


def text_ranges(text: str) -> str:
    return ", ".join(f"U+{ord(c):04X}" for c in sorted(set(text)))


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    produced: set[str] = set()
    blocks: list[str] = []

    for stem, source, family, style, subsets in FACES:
        items = (
            [(name, RANGES[name], parse_ranges(RANGES[name])) for name in subsets]
            if isinstance(subsets, list)
            else [(name, text_ranges(text), [ord(c) for c in text]) for name, text in subsets.items()]
        )
        for name, css_range, unicodes in items:
            filename = f"{stem}.{name}.woff2"
            cut(SRC / source, OUT / filename, unicodes)
            produced.add(filename)
            size = (OUT / filename).stat().st_size
            print(f"{filename:32} {size / 1024:6.1f} KB")
            blocks.append(
                "@font-face {\n"
                f'  font-family: "{family}";\n'
                f"  font-style: {style};\n"
                "  font-weight: normal;\n"
                "  font-display: swap;\n"
                f'  src: url("{URL}/{filename}") format("woff2");\n'
                f"  unicode-range: {css_range};\n"
                "}\n"
            )

    for stale in OUT.iterdir():
        if stale.is_file() and stale.name not in produced:
            try:
                stale.unlink()
                print(f"removed {stale.name}")
            except PermissionError:
                print(f"could not remove {stale.name} (read-only or in use)")

    header = (
        "/* Generated by scripts/subset-fonts.py — edit the script, not this file.\n"
        " * Nagara Body: Philosopher (regular + italic). Nagara Header: Zen\n"
        " * Kurenaido. Nagara Display: TorukSC (wordmark cut). */\n"
    )
    CSS.write_text(header + "\n" + "\n".join(blocks), encoding="utf-8", newline="\n")
    print(f"wrote {CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
